"""Shared fixtures + eval-table generation.

Every scenario test fills `evalrow` (scenario / expected / actual / notes). A
pytest hook records the real pass/fail outcome, and at session end the rows
are written to EVAL_TABLE.md and eval_results.json. The table is therefore
generated by the test run, never hand-written.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from errand_agent.agent import ErrandAgent, Limits  # noqa: E402
from errand_agent.clock import FakeClock  # noqa: E402
from errand_agent.context import ContextBuilder  # noqa: E402
from errand_agent.llm import ScriptedModel  # noqa: E402
from errand_agent.mocks import MockToolEnvironment, ScenarioConfig  # noqa: E402
from errand_agent.trace import Tracer  # noqa: E402

EVAL_ROWS: list[dict] = []
START = datetime(2026, 11, 9, 8, 0)  # a Monday


class Harness:
    """One scenario's world: fake clock, mock env, agent, tracer. Supports 'restart'."""

    def __init__(self, tmp_path: Path, config: ScenarioConfig | None = None, model=None, limits: Limits | None = None,
                 context: ContextBuilder | None = None, crash_hook=None):
        self.dir = tmp_path
        self.clock = FakeClock(START)
        self.config = config or ScenarioConfig(book_outcomes=["success"])
        self.env = MockToolEnvironment(tmp_path / "env.json", self.clock, self.config)
        self.model = model or ScriptedModel()
        self.limits = limits
        self.context = context
        self.crash_hook = crash_hook
        self.tracer = Tracer(tmp_path / "traces", run_id="test")
        self.agent = self._make()

    def _make(self) -> ErrandAgent:
        return ErrandAgent(self.env, self.model, self.dir, self.clock, tracer=self.tracer, limits=self.limits,
                           context=self.context, crash_hook=self.crash_hook)

    def restart(self, model=None, crash_hook=None):
        """Simulate a process restart: new env + agent instances over the same files."""
        self.env = MockToolEnvironment(self.dir / "env.json", self.clock, self.config)
        if model is not None:
            self.model = model
        self.crash_hook = crash_hook
        self.agent = self._make()
        return self.agent

    # convenience
    def say(self, text: str):
        return self.agent.handle(text)

    def book_calls(self) -> list[dict]:
        return [c for c in self.env.call_log if c["tool"] == "book"]

    def confirmed_bookings(self) -> list[dict]:
        return [b for b in self.env.state["bookings"].values() if b["status"] in ("confirmed", "rescheduled")]

    def events(self, *types: str) -> list[dict]:
        return self.tracer.of_type(*types)


@pytest.fixture
def harness(tmp_path):
    return lambda **kw: Harness(tmp_path, **kw)


@pytest.fixture
def evalrow(request):
    row = {"scenario": request.node.name.replace("test_", ""), "expected": "", "actual": "", "notes": ""}
    request.node._evalrow = row
    return row


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    rep = outcome.get_result()
    if rep.when == "call" and hasattr(item, "_evalrow"):
        row = dict(item._evalrow)
        row["result"] = "PASS" if rep.passed else "FAIL"
        if rep.failed:
            row["notes"] = (row["notes"] + " | " if row["notes"] else "") + str(rep.longrepr).splitlines()[-1][:160]
        EVAL_ROWS.append(row)


def pytest_sessionfinish(session, exitstatus):
    if not EVAL_ROWS:
        return
    out_md = ROOT / "EVAL_TABLE.md"
    out_json = ROOT / "eval_results.json"
    passed = sum(1 for r in EVAL_ROWS if r["result"] == "PASS")
    lines = [
        "# Evaluation table",
        "",
        f"Generated by `pytest` on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} - {passed}/{len(EVAL_ROWS)} scenarios passed.",
        "Offline run against the deterministic scripted model; no network calls.",
        "",
        "| # | Scenario | Expected | Actual | Result | Notes |",
        "|---|----------|----------|--------|--------|-------|",
    ]
    for i, r in enumerate(EVAL_ROWS, 1):
        esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")  # noqa: E731
        lines.append(f"| {i} | {esc(r['scenario'])} | {esc(r['expected'])} | {esc(r['actual'])} | {r['result']} | {esc(r['notes'])} |")
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    out_json.write_text(json.dumps(EVAL_ROWS, indent=2, ensure_ascii=False), encoding="utf-8")
